import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
sns.set_theme(style = "whitegrid")

print("Titanic loyihasi!")

df = pd.read_csv("/content/train.csv") #Datasetimizni train qismini yuklab olamiz
df.head() #ma'lumotlarni boshidagi 5 qatorini ko'ramiz

df.shape #datasetimiz qator va ustunlarni ko'ramiz :12 ustun , 891 qator

