df.isnull().sum() #Bo'sh qiymatlarni tekshiramiz: Age: 177 ta , Cabin : 687 ta , Embarked : 2 ta bo'sh qiymat bor

print("Ustunlar:") #datasetdagi barcha ustunlarni chiqaradi
print(df.columns.tolist())

print("\nSurvived qiymatlari:") #nechta yo‘lovchi omon qolgan va nechta omon qolmaganini
